"""presentation/numbers_geo.tex: macros for the geometry-story deck, generated from results/geometry_story/arms_summary.csv."""
import os, re
import pandas as pd
from isbi import common as C
S = pd.read_csv(os.path.join(C.ISBI, "results", "geometry_story", "arms_summary.csv"))
ALIAS = {"SAINT-P learned": "SaintL", "I3Net-P learned": "IthreeL", "SAINT exposure learned": "SaintExp",
         "I3Net exposure learned": "IthreeExp", "SAINT-PG learned": "SaintPG", "SAINT-PGX learned": "SaintPGX",
         "ArSSR-P learned": "ArssrL", "SAINT-P post-hoc": "SaintPH", "I3Net-P post-hoc": "IthreePH",
         "ArSSR-P post-hoc": "ArssrPH", "linear post-hoc": "LinPH", "SAINT-P post-hoc, no geometry": "SaintPHnogeo",
         "I3Net-P post-hoc, no geometry": "IthreePHnogeo", "linear post-hoc, no geometry": "LinPHnogeo",
         "SAINT-P constant width": "SaintCW", "ArSSR-P post-hoc, gap-conditional": "ArssrGC",
         "linear post-hoc, gap-conditional": "LinGC", "SAINT-P post-hoc, gap-conditional": "SaintGC",
         "I3Net-P post-hoc, gap-conditional": "IthreeGC"}
L = ["% generated by scripts/make_slide_numbers_geo.py -- do not edit"]
for r in S.itertuples():
    t = ALIAS[r.arm] + ("Four" if r.R == 4 else "Eight")
    L += [f"\\newcommand{{\\cu{t}}}{{{r.cov90_uniform:.2f}}}", f"\\newcommand{{\\cc{t}}}{{{r.cov90_clustered:.2f}}}",
          f"\\newcommand{{\\dc{t}}}{{{r.dcov90:+.2f}}}", f"\\newcommand{{\\wr{t}}}{{{r.width_ratio:.2f}}}"]
L.append(f"\\newcommand{{\\nTestGeo}}{{{int(S.n.iloc[0])}}}")
open(os.path.join(C.ISBI, "presentation", "numbers_geo.tex"), "w").write("\n".join(L) + "\n")
print(len(L), "macros")
