"""Write presentation/numbers.tex and presentation/tab_main.tex from the saved result CSVs only.

Every number on the slides comes from here, so slides and saved results cannot diverge.
"""
import json
import os

import pandas as pd

from isbi import common as C

RES = os.environ.get("ISBI_RES", os.path.join(C.ISBI, "results"))
OUT = os.environ.get("ISBI_PRES", os.path.join(C.ISBI, "presentation"))
rt = pd.read_csv(os.path.join(RES, "table_recon.csv"))
it = pd.read_csv(os.path.join(RES, "table_intervals.csv"))
kt = pd.read_csv(os.path.join(RES, "table_ranking.csv"))
pe = pd.read_csv(os.path.join(RES, "primary_endpoint.csv"))
cnt = json.load(open(os.path.join(RES, "counts.json")))
proto = json.load(open(os.path.join(C.ISBI, "configs", "protocol_frozen.json"))) if os.path.exists(
    os.path.join(C.ISBI, "configs", "protocol_frozen.json")) else {}

mac = {}


def m(name, val, fmt="{:.3f}"):
    mac[name] = fmt.format(val) if not isinstance(val, str) else val


m("nTest", cnt["n_test_patients"], "{:d}")
m("nCases", cnt["n_cases"], "{:d}")
for a in ("SAINT", "I3Net"):
    for R in C.STRIDES:
        tag = f"{a.replace('I3Net', 'IThreeNet')}{'Four' if R == 4 else 'Eight'}"
        r = pe[(pe.arch == a) & (pe.R == R) & pe.contrast.str.contains("PRIMARY")].iloc[0]
        m(f"prim{tag}", r["mean"], "{:+.3f}")
        m(f"prim{tag}CI", f"[{r.ci_lo:+.3f}, {r.ci_hi:+.3f}]")
        for kind in ("learned_cal", "posthoc", "learned_raw", "const"):
            q = pe[(pe.arch == a) & (pe.R == R) & (pe.contrast == f"dcov90[{kind}] clustered-uniform")].iloc[0]
            k = {"learned_cal": "L", "posthoc": "P", "learned_raw": "Raw", "const": "W"}[kind]
            m(f"d{k}{tag}", q["mean"], "{:+.3f}")
            m(f"d{k}{tag}CI", f"[{q.ci_lo:+.3f}, {q.ci_hi:+.3f}]")
            m(f"wr{k}{tag}", q.width_ratio_clu_over_uni, "{:.2f}")
open(os.path.join(OUT, "numbers.tex"), "w").write(
    "% generated by scripts/make_slide_numbers.py -- do not edit\n" +
    "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in mac.items()) + "\n")

# ---------------------------------------------------------------- main table (x4)
def cell(df, **kw):
    q = df
    for k, v in kw.items():
        q = q[q[k] == v]
    return q.iloc[0] if len(q) else None


lines = []
for a in ("SAINT", "I3Net"):
    for pat in ("uniform", "clustered"):
        r_rec = cell(rt, method=f"{a}_P", pattern=pat, R=4)
        r_lin = cell(rt, method="linear", pattern=pat, R=4)
        L = cell(it, arm=f"{a}_P|learned_cal", pattern=pat, R=4)
        Pp = cell(it, arm=f"{a}_P|posthoc", pattern=pat, R=4)
        kL = cell(kt, mean=f"{a}_P", score="learned_total", pattern=pat, R=4)
        kP = cell(kt, mean=f"{a}_P", score="posthoc", pattern=pat, R=4)
        kG = cell(kt, mean=f"{a}_P", score="near_mm", pattern=pat, R=4)
        lines.append(
            f"{a}-P & {pat} & {r_rec.psnr_mean:.2f} ({r_lin.psnr_mean:.2f}) & "
            f"{L.cov90_mean:.3f} / {Pp.cov90_mean:.3f} & {L.width90_mean:.3f} / {Pp.width90_mean:.3f} & "
            f"{kL.strat_spearman_mean:.2f} / {kP.strat_spearman_mean:.2f} & {kG.spearman_mean:.2f} \\\\")
    lines.append("\\addlinespace[2pt]")
open(os.path.join(OUT, "tab_main.tex"), "w").write("% generated by scripts/make_slide_numbers.py\n" + "\n".join(lines[:-1]) + "\n")
print(open(os.path.join(OUT, "numbers.tex")).read())
print("\n".join(lines))
